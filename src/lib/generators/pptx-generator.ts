import type { Diagram } from "@/types/diagram"
import { artifactLabel, artifactSummary, getAllArtifactsContent, stringifyArtifact } from "@/lib/generators/artifact-serialization"

export class PPTXGenerator {
  private diagram: Diagram

  constructor(diagram: Diagram) {
    this.diagram = diagram
  }

  async generate(): Promise<Buffer> {
    const PptxGenJS = (await import("pptxgenjs")).default
    const pptx = new PptxGenJS()
    pptx.layout = "LAYOUT_WIDE"
    pptx.author = "Blueprinta"
    pptx.subject = "Software architecture blueprint"
    pptx.title = this.diagram.title

    const artifacts = getAllArtifactsContent(this.diagram) ?? {}
    const titleSlide = pptx.addSlide()
    titleSlide.background = { color: "0F172A" }
    titleSlide.addText(this.diagram.title || "Blueprinta Project", {
      x: 0.7, y: 1.4, w: 11.8, h: 0.7, fontSize: 30, bold: true, color: "FFFFFF",
    })
    titleSlide.addText(this.diagram.description || "Multi-agent software architecture blueprint", {
      x: 0.7, y: 2.25, w: 10.8, h: 0.6, fontSize: 16, color: "CBD5E1",
    })
    titleSlide.addText(`Generated by Blueprinta • ${Object.keys(artifacts).length} artifacts`, {
      x: 0.7, y: 6.55, w: 8, h: 0.3, fontSize: 10, color: "94A3B8",
    })

    const overviewSlide = pptx.addSlide()
    overviewSlide.addText("Blueprint overview", {
      x: 0.6, y: 0.45, w: 12, h: 0.4, fontSize: 24, bold: true, color: "0F172A",
    })
    overviewSlide.addText(Object.keys(artifacts).map((key) => `• ${artifactLabel(key)}`).join("\n") || "No artifacts available", {
      x: 0.8, y: 1.3, w: 5.5, h: 4.8, fontSize: 18, color: "334155", valign: "middle",
    })
    overviewSlide.addShape(pptx.ShapeType.roundRect, {
      x: 7.1, y: 1.35, w: 4.8, h: 3.2, rectRadius: 0.08, fill: { color: "EFF6FF" }, line: { color: "BFDBFE" },
    })
    overviewSlide.addText("Artifacts are organized into dedicated slides with a concise summary and a structured-data preview.", {
      x: 7.55, y: 2.15, w: 3.9, h: 1.6, fontSize: 17, color: "1E3A8A", valign: "middle", align: "center",
    })

    for (const [key, content] of Object.entries(artifacts)) {
      const slide = pptx.addSlide()
      const summary = artifactSummary(content) || "Review the structured data preview for this artifact."
      const preview = stringifyArtifact(content).slice(0, 1_500)
      slide.addText(artifactLabel(key), {
        x: 0.6, y: 0.45, w: 12, h: 0.4, fontSize: 24, bold: true, color: "0F172A",
      })
      slide.addText(summary, {
        x: 0.7, y: 1.15, w: 11.8, h: 0.8, fontSize: 14, color: "334155", fit: "shrink",
      })
      slide.addShape(pptx.ShapeType.roundRect, {
        x: 0.65, y: 2.15, w: 12, h: 4.45, rectRadius: 0.04, fill: { color: "F8FAFC" }, line: { color: "E2E8F0" },
      })
      slide.addText(preview, {
        x: 0.9, y: 2.42, w: 11.5, h: 3.9, fontFace: "Courier New", fontSize: 9, color: "334155", fit: "shrink", margin: 0,
      })
    }

    return (await pptx.write({ outputType: "nodebuffer" })) as Buffer
  }
}
